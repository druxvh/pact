-- pact: VibeParty over Supabase Realtime — who may listen and announce on a party's channel.
--
-- A party is one private Realtime channel per room, with the topic `party:<room code>`. People talk to each other through
-- two Realtime features on it: Broadcast (playback, chat, queue…) and Presence (who is here, who is hosting). Nothing is
-- stored — there is no table. The only thing the database decides is whether a signed-in user may join the channel at all,
-- and that is what these policies on `realtime.messages` do.
--
--   * Only the `authenticated` role. The anonymous key can neither listen nor announce, so a guest can't join a live party
--     (and can't probe whether a room exists).
--   * Only a topic of exactly the shape `party:` + a room code (lower-case letters, digits and single dashes, 4–32
--     characters — the same rule as src/features/party/roomCode.ts). Any other topic is not covered by a policy, so it is
--     denied by default: this migration does not open up the rest of Realtime.
--   * Only the `broadcast` and `presence` extensions. (`postgres_changes` is authorised by table RLS, not by this table.)
--
-- The room code *is* the password — like an unlisted link. Whoever holds it can join, which is the product's model; nothing in
-- the database knows who is "in" a room, on purpose (that would need a table to garbage-collect and a join step before every
-- party). Treat codes accordingly: they are 52 random bits when generated by pact.
--
-- Dashboard: Realtime → Settings → "Allow public access" must be OFF. With it ON, anyone with the publishable key could use
-- *public* channels, and (more to the point) private-channel authorization is what makes these policies the gatekeeper.

-- Pure shape check. IMMUTABLE and with an empty search_path like every helper in `private`; no table access, so it is not
-- SECURITY DEFINER (nothing to elevate).
create function private.party_topic(topic text) returns boolean
language sql immutable set search_path = ''
as $$
  select coalesce(topic ~ '^party:[a-z0-9]+(-[a-z0-9]+)*$' and length(topic) between 10 and 38, false)
$$;
grant execute on function private.party_topic(text) to authenticated;

create policy "party: listen" on realtime.messages for select to authenticated
  using (
    (select auth.uid()) is not null
    and realtime.messages.extension in ('broadcast', 'presence')
    and private.party_topic((select realtime.topic()))
  );

create policy "party: announce" on realtime.messages for insert to authenticated
  with check (
    (select auth.uid()) is not null
    and realtime.messages.extension in ('broadcast', 'presence')
    and private.party_topic((select realtime.topic()))
  );
